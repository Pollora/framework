<?php

declare(strict_types=1);

use Pollora\Support\Domain\StringHelper;

/*
 * Non-regression: freezes what StringHelper::plural() returns today, quirks included
 * ('safe' => 'saves', 'posts' => 'postses'), so that restructuring its rules cannot change a result.
